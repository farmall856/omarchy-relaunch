//! Lua pin emission. Mirrors the bash engine's `lua_rules` byte-for-byte so the
//! generated `o.window` rules behave identically, but is driven only from a
//! verified `SignedConfig` and emitted by the root-owned anchor at login — the
//! on-disk `rules.lua` is never executed.

use relaunch_core::{Entry, SignedConfig};

/// Escape a class for a Hyprland POSIX-ERE class match (`^(...)$`), matching the
/// engine's `regex_escape`.
fn regex_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if matches!(
            c,
            '\\' | '.' | '+' | '*' | '?' | '(' | ')' | '[' | ']' | '{' | '}' | '^' | '$' | '|'
        ) {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// Escape for embedding the regex in a Lua `"..."` string: double every
/// backslash (including the ones `regex_escape` added) and escape quotes.
/// Equals the engine's `lua_regex`.
pub fn lua_regex(s: &str) -> String {
    regex_escape(s).replace('\\', "\\\\").replace('"', "\\\"")
}

fn pin_for(e: &Entry) -> String {
    let lr = lua_regex(&e.class);
    let mut out = String::new();
    // A tiled window must first lose the Omarchy +floating-window tag, or
    // system.lua floats it by tag regardless of the tile rule.
    if e.float == Some(false) {
        out.push_str(&format!(
            "o.window({{ class = \"^({lr})$\" }}, {{ tag = \"-floating-window\" }})\n"
        ));
    }
    out.push_str(&format!(
        "o.window({{ class = \"^({lr})$\" }}, {{ workspace = \"{} silent\"",
        e.workspace
    ));
    match e.float {
        Some(true) => out.push_str(", float = true"),
        Some(false) => out.push_str(", tile = true"),
        None => {}
    }
    out.push_str(" })\n");
    out
}

/// The single constant boot handler. Emitted only when the config verified; it
/// re-verifies before launching anything (see `boot`).
pub const BOOT_REGISTRATION: &str =
    "o.exec_on_start(\"/usr/lib/omarchy-relaunch/relaunch-anchor boot\")\n";

/// Emit the pins for every enabled entry, followed by the boot registration.
/// Called only after the signature and state verified.
pub fn emit(cfg: &SignedConfig) -> String {
    let mut out =
        String::from("-- Generated by relaunch-anchor from the signed config. Do not edit.\n");
    // Match the engine's `enabled_entries` ordering (workspace, then class) so
    // the emitted rules read identically. Order is cosmetic: pins are per-class
    // standing rules and classes are unique.
    let mut enabled: Vec<&Entry> = cfg.entries.iter().filter(|e| e.enabled).collect();
    enabled.sort_by(|a, b| {
        a.workspace
            .cmp(&b.workspace)
            .then_with(|| a.class.as_bytes().cmp(b.class.as_bytes()))
    });
    for e in enabled {
        out.push_str(&pin_for(e));
    }
    out.push_str(BOOT_REGISTRATION);
    out
}
