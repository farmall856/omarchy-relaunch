func GuessExec(class string) string {
	if e, ok := knownExec[class]; ok {
		return e
	}
	return strings.ToLower(class)
}

func (c *Config) enabledSorted() []Entry {
	entries := make([]Entry, 0, len(c.Entries))
	for _, e := range c.Entries {
		if e.Enabled && e.Class != "" && e.Workspace > 0 {
			entries = append(entries, e)
		}
	}
	sort.Slice(entries, func(i, j int) bool {
		if entries[i].Workspace != entries[j].Workspace {
			return entries[i].Workspace < entries[j].Workspace
		}
		return entries[i].Class < entries[j].Class
	})
	return entries
}

func (c *Config) Snippet() string {
	entries := c.enabledSorted()
	var b strings.Builder
	b.WriteString("# Generated by omarchy-relaunch. Do not edit by hand.\n")
	b.WriteString("# Regenerate via the bar widget or `relaunch generate`.\n\n")
	b.WriteString("# --- Workspace pinning rules ---\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "windowrulev2 = workspace %d silent, class:^(%s)$\n",
			e.Workspace, regexEscape(e.Class))
		if e.Float {
			fmt.Fprintf(&b, "windowrulev2 = float, class:^(%s)$\n", regexEscape(e.Class))
		}
	}
	b.WriteString("\n# --- Launch at startup ---\n")
	for _, e := range entries {
		ex := e.Exec
		if ex == "" {
			ex = GuessExec(e.Class)
		}
		if c.StaggerSeconds > 0 {
			fmt.Fprintf(&b, "exec-once = sleep %d && %s\n", c.StaggerSeconds, ex)
		} else {
			fmt.Fprintf(&b, "exec-once = %s\n", ex)
		}
	}
	return b.String()
}

func (c *Config) WriteSnippet() error {
	p := SnippetPath()
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	tmp := p + ".tmp"
	if err := os.WriteFile(tmp, []byte(c.Snippet()), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, p)
}

func regexEscape(s string) string {
	r := strings.NewReplacer(
		".", `\.`, "+", `\+`, "*", `\*`, "?", `\?`,
		"(", `\(`, ")", `\)`, "[", `\[`, "]", `\]`,
		"{", `\{`, "}", `\}`, "^", `\^`, "$", `\$`, "|", `\|`,
	)
	return r.Replace(s)
}
