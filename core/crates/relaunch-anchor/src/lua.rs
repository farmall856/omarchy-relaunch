//! What `emit-lua` prints for Hyprland to evaluate at login. Placement is
//! launch-and-move (`boot`), so there are no window rules: a verified document
//! yields only the constant boot registration, and the on-disk `rules.lua` is
//! never executed.

use relaunch_core::SignedConfig;

/// The single constant boot handler. Emitted only when the config verified; it
/// re-verifies before launching anything (see `boot`).
pub const BOOT_REGISTRATION: &str =
    "o.exec_on_start(\"/usr/lib/omarchy-relaunch/relaunch-anchor boot\")\n";

/// The Lua for a verified document: the boot registration and nothing that
/// depends on the document's contents. Taking the document keeps the call
/// reachable only after verification succeeded.
#[must_use]
pub fn emit(_verified: &SignedConfig) -> String {
    format!(
        "-- Generated by relaunch-anchor from the signed config. Do not edit.\n{BOOT_REGISTRATION}"
    )
}
