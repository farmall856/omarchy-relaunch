// Package config models the app->workspace table, persists it, and generates
// the Hyprland snippet (windowrulev2 + exec-once) that does the relaunch.
package config

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type Entry struct {
	Class     string `json:"class"`
	Workspace int    `json:"workspace"`
	Exec      string `json:"exec"`
	Enabled   bool   `json:"enabled"`
	Float     bool   `json:"float,omitempty"`
}

type Config struct {
	StaggerSeconds int     `json:"staggerSeconds"`
	Entries        []Entry `json:"entries"`
}

func configDir() string {
	base := os.Getenv("XDG_CONFIG_HOME")
	if base == "" {
		base = filepath.Join(os.Getenv("HOME"), ".config")
	}
	return filepath.Join(base, "omarchy-relaunch")
}

func DefaultPath() string { return filepath.Join(configDir(), "config.json") }
func SnippetPath() string { return filepath.Join(configDir(), "relaunch.conf") }

func Load() (*Config, error) {
	c := &Config{}
	b, err := os.ReadFile(DefaultPath())
	if os.IsNotExist(err) {
		return c, nil
	}
	if err != nil {
		return nil, err
	}
	if err := json.Unmarshal(b, c); err != nil {
		return nil, fmt.Errorf("parse config: %w", err)
	}
	return c, nil
}

func (c *Config) Save() error {
	p := DefaultPath()
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	b, err := json.MarshalIndent(c, "", "  ")
	if err != nil {
		return err
	}
	tmp := p + ".tmp"
	if err := os.WriteFile(tmp, b, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, p)
}

